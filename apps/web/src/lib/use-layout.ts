'use client';
import { useEffect, useState, useSyncExternalStore, type RefObject } from 'react';

/** Media query no cliente (no servidor: false, layout de celular). */
export function useMediaQuery(query: string): boolean {
  return useSyncExternalStore(
    (onChange) => {
      const mql = window.matchMedia(query);
      mql.addEventListener('change', onChange);
      return () => mql.removeEventListener('change', onChange);
    },
    () => window.matchMedia(query).matches,
    () => false,
  );
}

/** Tamanho (px) de um elemento, atualizado por ResizeObserver. */
export function useElementSize(ref: RefObject<HTMLElement | null>): {
  width: number;
  height: number;
} {
  const [size, setSize] = useState({ width: 0, height: 0 });
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const ro = new ResizeObserver(([entry]) => {
      const box = entry!.borderBoxSize?.[0];
      const width = Math.round(box ? box.inlineSize : el.offsetWidth);
      const height = Math.round(box ? box.blockSize : el.offsetHeight);
      setSize((s) => (s.width === width && s.height === height ? s : { width, height }));
    });
    ro.observe(el);
    return () => ro.disconnect();
  }, [ref]);
  return size;
}
